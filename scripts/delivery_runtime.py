#!/usr/bin/env python3
"""§12.6: путь, который проверяется только исполнением.

Часть `delivery_check.py` (`delivery@1.53`). Класс отказов, невидимый всем
статическим оракулам: платформа отвечает падением процесса, а не кодом ошибки.
"""

from __future__ import annotations

import fnmatch
import re

from delivery_base import DEFAULT_BREAKERS, field, is_placeholder

# --- §12.6: путь, который проверяется только исполнением ---------------------
# Есть класс отказов, невидимый ВСЕМ статическим оракулам и необрабатываемый в
# рантайме: платформа отвечает на нарушение политики смертью процесса, а не кодом
# ошибки. Замер (iOS, четыре падения за сутки, разбор в поле): нет ключа в
# Info.plist — падение; запрос снимка сверх потолка выхода — NSException; чтение
# библиотеки под правом «только добавлять» — падение от TCC. Ни одно не возвращает
# ошибку, которую можно поймать. Сборка при этом ЗЕЛЁНАЯ во всех трёх случаях.
#
# Отсюда правило: такой путь обязан быть ИСПОЛНЕН до handoff. Не «покрыт тестом» —
# исполнен на целевой среде, потому что именно среда и выносит вердикт.
#
# Почему это отдельно от §12.5, хотя механика похожа. §12.5 доказывает, что дифф
# ПРОЧИТАН, и этого достаточно для «архитектура неудачна». Здесь чтение не
# помогает вовсе: все четыре отказа были в коде, который автор читал и считал
# верным. Рассуждение о правах — не проверка прав; замер поля прямо это назвал
# («я рассуждал о правах вместо того, чтобы их проверить»).
def runtime_surfaces(status: str) -> tuple[set[str], bool]:
    """(объявленные пути, объявлено ли осознанно) из строки `runtime_paths:`.

    Второе значение отличает «объявили `none reason=…`» от «поля нет вовсе».
    Разница ровно та же, что у `n/a` без причины в остальном каноне: не думали и
    подумали-и-нет — разные состояния, и молчание не должно выглядеть как ответ.
    """
    raw = field(status, "runtime_paths")
    if is_placeholder(raw):
        return set(), False
    if re.match(r"(?i)^\s*none\b", raw):
        # `none` без причины — то же, что его отсутствие: см. `n/a reason=` у
        # `diagnosis:`. Слово «none» само по себе ничего не сообщает.
        return set(), bool(re.search(r"(?i)reason\s*=\s*\S", raw))
    return {p.strip() for p in raw.split(",") if p.strip()}, True


def breaker_value(status: str, name: str) -> int:
    """Порог breaker'а с учётом ЗАКОННОГО override, без дублирования принуждения.

    Override принимается по тому же правилу, что у остальных breaker'ов §3.4:
    либо строка `circuit_breakers:`, либо подписанный waiver (`reason=` +
    `by=human:`). Ругается на неподписанный override НЕ здесь, а тот же парсер,
    что и для `max_files_touched` — ключ лежит в `DEFAULT_BREAKERS`, поэтому
    ветка ошибки достаётся ему. Две реализации одного правила разъехались бы
    при первой же правке, а тут это значило бы «лимит поднят молча».
    """
    val = DEFAULT_BREAKERS.get(name, 1)
    for m in re.finditer(rf"({re.escape(name)})[ \t]*=[ \t]*(\d+)", status):
        bol = status.rfind("\n", 0, m.start()) + 1
        eol = status.find("\n", m.end())
        line = status[bol: eol if eol != -1 else len(status)]
        low = line.lower()
        if "circuit_breakers" in low or ("reason=" in low and "by=human:" in low):
            val = int(m.group(2))
    return val


def runtime_touched(paths: list[str], surfaces: set[str]) -> set[str]:
    """Какие объявленные поверхности задел дифф.

    Совпадение по префиксу И по glob: проект объявляет либо каталог
    (`ios/LashTryOn/Camera/`), либо маску (`**/Capture*.swift`). Требовать одну
    форму значило бы заставить подгонять раскладку под гейт.
    """
    hit: set[str] = set()
    for s in surfaces:
        pat = s.strip().rstrip("/")
        for p in paths:
            if p.startswith(pat + "/") or p == pat or fnmatch.fnmatch(p, s):
                hit.add(s)
                break
    return hit


def runtime_proof_gaps(report: str, touched: set[str]) -> list[str]:
    """Чего не хватает в записи об исполнении.

    ⚠ Прямо о пределе, как это делает §12.5 про своё: **доказательства, что
    прогон был, здесь нет и быть не может** — есть доказательство, что про
    КАЖДУЮ задетую поверхность сделано конкретное утверждение с датой и названа
    команда. Это ловит не ложь, а пропуск, и пропуск — ровно то, что случилось
    все четыре раза: путь не был исполнен НИ РАЗУ, а не исполнен плохо.
    """
    if not touched:
        return []
    block = re.search(
        r"(?ims)^#{1,4}\s*(?:исполнение\s+рисковых|runtime\s+run)\b.*?(?=^#{1,4}\s|\Z)",
        report,
    )
    if not block:
        return [
            "нет блока «## Исполнение рисковых путей» (§12.6) — дифф задел: "
            + ", ".join(sorted(touched))
            + ". Это пути, чей отказ не виден ни сборке, ни тестам — падением "
              "процесса (права, платформа) или молча (раскладка экрана). Нужен "
              "не вывод, что всё должно работать, а строка «прогнал <что>, "
              "увидел <что> at=<дата>»"
        ]
    body = block.group(0)
    low = body.lower()
    gaps: list[str] = []

    # Каждая задетая поверхность — своя строка. «Прогнал, всё ок» одной строкой
    # на три поверхности это отписка по частям, и §12.5 уже платила за то, чтобы
    # это понять: там пробой прошёл блоком с одним классом из трёх.
    # Поверхность считается названной ДВУМЯ способами: написали её саму
    # (`ios/UI/`) или назвали её содержательный сегмент (`Camera`, `Capture`).
    #
    # ⚠ Одних сегментов НЕ хватает, и это поймал собственный тест: у `ios/UI/`
    # нет ни одного куска длиннее трёх символов, поэтому удовлетворить проверку
    # было нечем ВООБЩЕ — гейт, который не пройти. Ложное срабатывание тут
    # дороже пропуска: §4.3b, такую проверку снимают с проекта за неделю вместе
    # с пользой. Сначала ищем саму строку пути, сегменты — только запасной путь
    # для глобов вида `**/Capture*.swift`.
    def named(s: str) -> bool:
        if s.strip().rstrip("/").lower() in low:
            return True
        return any(tok and tok.lower() in low
                   for tok in re.split(r"[/*]", s) if len(tok) > 3)

    silent = [s for s in sorted(touched) if not named(s)]
    if silent:
        gaps.append(
            "в блоке исполнения не названы задетые пути: " + ", ".join(silent)
            + " (§12.6) — на каждый нужна своя строка: исполнять их надо по "
              "одному, иначе отказ приходит составным и разбирается перебором"
        )
    if not re.search(r"(?i)\bat\s*=\s*\d", body):
        gaps.append(
            "в блоке исполнения нет отметки `at=<дата>` (§12.6) — прогон без "
            "даты неотличим от прогона до правки, а именно так и выглядел бы "
            "самый вероятный обход"
        )
    if "`" not in body:
        gaps.append(
            "в блоке исполнения не названа команда (§12.6) — впиши в backticks "
            "то, ЧЕМ исполнял (`-scanShot 1`, `plutil -p …`): инструмент, "
            "которого нельзя повторить, следующий раз будет выброшен, а не починен"
        )
    return gaps


